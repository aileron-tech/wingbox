"""Links that no import states: a file a generator writes, and a script another file launches.

Three sources, each with its basis:

- declared: `generators:` in `.wingbox/config.yaml`, a list of `{run, inputs, outputs}` with paths
  relative to the repository root (`*` and `**` are allowed in `inputs` and `outputs`);
- inferred, from the generated file: a line among its first ten that starts with
  `Generated by <path>` and, optionally, names the input with `edit <path>` or `generated from <path>`;
- inferred, from the build files: `add_custom_command(OUTPUT ... COMMAND ... DEPENDS ...)` of a
  CMake file.

A link is `generated` (the generated file depends on its generator and on the inputs) or `runs`
(a file launches a script, read by the language parser). A path that a declaration names and the
repository does not hold is unresolved: reported, never guessed.

Standard library only; PyYAML is asked for only when the config file has the key.
"""
from __future__ import annotations

import glob
import os
import re
from dataclasses import dataclass
from typing import Callable, Iterable, Optional, Sequence

CONFIG_FILE = ".wingbox/config.yaml"
CONFIG_KEY = "generators"
DECLARED = "declared"
INFERRED = "inferred"
MARKER_LINES = 10

# `Generated by tools/make_layouts.py; edit schema/formats.yaml.`
_PATH = r"[`'\"]?((?:[\w.\-]+[/\\])+[\w.\-]+\.[A-Za-z0-9_]+|[\w\-]+\.[A-Za-z0-9_]+)"
# The line speaks of the file itself: it starts with the phrase (after the comment signs), as in
# `// Generated by tools/gen.py`, `"""This file is generated by ...`, `# AUTO-GENERATED WITH ...`. A sentence
# that only contains the words (`Decodes the blocks generated by block_builder.cc`) is no marker.
_GENERATED_BY = re.compile(
    r"^[\s/*#;\"'<!@-]*(?:(?:this\s+)?(?:file|code|module|header|source)\s+(?:is|was|has\s+been)\s+)?"
    r"(?:auto(?:matically)?[\s-]*)?generated\s+(?:by|with|using)\s+" + _PATH, re.IGNORECASE)
_GENERATED_FROM = re.compile(r"\b(?:generated\s+from|edit|source:|input:)\s+" + _PATH, re.IGNORECASE)
_CUSTOM_COMMAND = re.compile(r"\badd_custom_command\s*\(((?:[^()]|\([^()]*\))*)\)", re.IGNORECASE)
_COMMAND_KEYWORDS = frozenset({
    "OUTPUT", "COMMAND", "DEPENDS", "MAIN_DEPENDENCY", "BYPRODUCTS", "WORKING_DIRECTORY", "COMMENT", "VERBATIM",
    "IMPLICIT_DEPENDS", "DEPFILE", "JOB_POOL", "USES_TERMINAL", "COMMAND_EXPAND_LISTS", "APPEND", "ARGS", "CODEGEN",
    "DEPENDS_EXPLICIT_ONLY", "JOB_SERVER_AWARE",
})
_CMAKE_HERE = ("${CMAKE_CURRENT_SOURCE_DIR}", "${CMAKE_CURRENT_LIST_DIR}")
_CMAKE_TOP = ("${PROJECT_SOURCE_DIR}", "${CMAKE_SOURCE_DIR}")


@dataclass(frozen=True)
class Link:
    kind: str      # generated: source is the generated file; runs: source is the file that launches
    source: str    # path relative to the repository root, with /
    target: str    # the generator or an input (generated); the launched script (runs)
    role: str      # by (the generator), from (an input), runs
    basis: str     # declared or inferred
    evidence: str  # where the link is stated: the config file, a marker line, a CMake file


@dataclass(frozen=True)
class Unresolved:
    path: str      # as the declaration names it
    role: str      # run, input or output
    basis: str
    evidence: str


def read_markers(content: str) -> list[dict]:
    """What the head of a file says about its own generation: [{"role": "by" or "from", "path": as written,
    "line": 1-based}], only when a `generated by` line is among the first ten lines."""
    found: list[dict] = []
    lines = content.split("\n", MARKER_LINES)[:MARKER_LINES]
    if not any("generated" in line.lower() for line in lines):
        return found
    for number, line in enumerate(lines, start=1):
        for role, pattern in (("by", _GENERATED_BY), ("from", _GENERATED_FROM)):
            for match in pattern.finditer(line):
                path = match.group(1).replace("\\", "/").rstrip(".")
                if "/" in path or role == "by":
                    found.append({"role": role, "path": path, "line": number})
    if not any(item["role"] == "by" for item in found):
        return []
    return found


def existing_file(root: str, written: str, beside: str = "") -> Optional[str]:
    """The file of the repository a written path names: from the root, then beside the file that names it."""
    for base in ("", beside):
        candidate = os.path.normpath(os.path.join(base, written)).replace(os.sep, "/")
        if not candidate.startswith("../") and os.path.isfile(os.path.join(root, candidate)):
            return candidate
    return None


def marker_links(root: str, file: str, markers: Sequence[dict]) -> tuple[list[Link], list[Unresolved]]:
    """The links the markers of one file state. A path the repository does not hold is unresolved."""
    links: list[Link] = []
    unresolved: list[Unresolved] = []
    for marker in markers:
        evidence = f"{file} line {marker['line']}"
        target = existing_file(root, marker["path"], os.path.dirname(file))
        if target is None:
            unresolved.append(Unresolved(marker["path"], "run" if marker["role"] == "by" else "input", INFERRED, evidence))
        elif target != file:
            links.append(Link("generated", file, target, marker["role"], INFERRED, evidence))
    return links, unresolved


def _paths(root: str, pattern: str) -> list[str]:
    """The files of the repository a declared path or pattern names, sorted; none when nothing matches."""
    if any(character in pattern for character in "*?["):
        found = glob.glob(os.path.join(root, pattern), recursive=True)
        return sorted(os.path.relpath(path, root).replace(os.sep, "/") for path in found if os.path.isfile(path))
    path = os.path.normpath(pattern).replace(os.sep, "/")
    return [path] if os.path.isfile(os.path.join(root, path)) else []


def declared_links(root: str, read_text: Callable[[str], Optional[str]]) -> tuple[list[Link], list[Unresolved], str]:
    """(links, unresolved paths, error) of the `generators:` key of the config file. error: one line when
    the key is not a list of `{run, inputs, outputs}`; nothing is then declared."""
    text = read_text(CONFIG_FILE)
    if text is None or CONFIG_KEY not in text:
        return [], [], ""
    try:
        import yaml
    except ImportError:
        return [], [], f"{CONFIG_FILE}: `{CONFIG_KEY}` needs PyYAML"
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as error:
        return [], [], f"{CONFIG_FILE} is not valid YAML: {error}"
    entries = data.get(CONFIG_KEY) if isinstance(data, dict) else None
    if entries is None:
        return [], [], ""
    if not isinstance(entries, list):
        return [], [], f"{CONFIG_FILE}: `{CONFIG_KEY}` must be a list of entries with `run`, `inputs` and `outputs`"
    links: list[Link] = []
    unresolved: list[Unresolved] = []
    for number, entry in enumerate(entries, start=1):
        where = f"{CONFIG_FILE} {CONFIG_KEY}[{number}]"
        if not isinstance(entry, dict) or not isinstance(entry.get("outputs"), list) or not entry["outputs"]:
            return [], [], f"{where}: expected `outputs`, a list of generated files, with `run` and `inputs`"
        unknown = sorted(set(entry) - {"run", "inputs", "outputs"})
        if unknown:
            return [], [], f"{where}: unknown key {unknown[0]!r}; the keys are `run`, `inputs` and `outputs`"
        run = entry.get("run")
        inputs = entry.get("inputs") or []
        if (run is not None and not isinstance(run, str)) or not isinstance(inputs, list) \
                or not all(isinstance(item, str) for item in [*inputs, *entry["outputs"]]):
            return [], [], f"{where}: `run` is one path, `inputs` and `outputs` are lists of paths"
        targets: list[tuple[str, str]] = []
        if run is not None:
            runs = _paths(root, run)
            if runs:
                targets.append((runs[0], "by"))
            else:
                unresolved.append(Unresolved(run, "run", DECLARED, where))
        for pattern in inputs:
            matched = _paths(root, pattern)
            if not matched:
                unresolved.append(Unresolved(pattern, "input", DECLARED, where))
            targets.extend((path, "from") for path in matched)
        for pattern in entry["outputs"]:
            outputs = _paths(root, pattern)
            if not outputs:
                unresolved.append(Unresolved(pattern, "output", DECLARED, where))
            for output in outputs:
                links.extend(Link("generated", output, target, role, DECLARED, where) for target, role in targets if target != output)
    return links, unresolved, ""


def _cmake_path(root: str, token: str, here: str, tops: Sequence[str]) -> Optional[str]:
    """A CMake argument as a file of the repository: `${CMAKE_CURRENT_SOURCE_DIR}`, `${PROJECT_SOURCE_DIR}`
    and their kin, or a path relative to the folder of the CMake file; None for anything else."""
    token = token.strip('"')
    bases: Sequence[str] = (here,)
    for variables, variable_bases in ((_CMAKE_HERE, (here,)), (_CMAKE_TOP, tops)):
        variable = next((variable for variable in variables if token.startswith(variable)), None)
        if variable is not None:
            token = token[len(variable):].lstrip("/\\")
            bases = variable_bases
            break
    if not token or "$" in token or os.path.isabs(token):
        return None
    for base in bases:
        candidate = os.path.normpath(os.path.join(base, token)).replace(os.sep, "/")
        if not candidate.startswith("../") and os.path.isfile(os.path.join(root, candidate)):
            return candidate
    return None


def cmake_links(root: str, cmake_files: Iterable[str], read_text: Callable[[str], Optional[str]]) -> list[Link]:
    """The links of every `add_custom_command(OUTPUT ...)` whose outputs are files of the repository: each
    output is generated by the files of the repository its COMMAND names and from those of DEPENDS."""
    files = sorted(cmake_files)
    list_folders = {os.path.dirname(path) for path in files if os.path.basename(path) == "CMakeLists.txt"}
    links: list[Link] = []
    for path in files:
        text = read_text(path)
        if text is None or "add_custom_command" not in text.lower():
            continue
        here = os.path.dirname(path)
        above = []
        current = here
        while True:
            if current in list_folders:
                above.append(current)
            if not current:
                break
            current = os.path.dirname(current)
        scope = above[0] if above else here
        tops = list(reversed(above)) or [""]
        for call in _CUSTOM_COMMAND.finditer(text):
            sections: dict[str, list[str]] = {}
            section = ""
            for token in call.group(1).split():
                if token in _COMMAND_KEYWORDS:
                    section = token
                elif section:
                    sections.setdefault(section, []).append(token)
            outputs = [found for token in sections.get("OUTPUT", []) if (found := _cmake_path(root, token, scope, tops))]
            if not outputs:
                continue
            targets = [(found, "by") for token in sections.get("COMMAND", []) if (found := _cmake_path(root, token, scope, tops))]
            targets += [(found, "from") for token in sections.get("DEPENDS", []) + sections.get("MAIN_DEPENDENCY", [])
                        if (found := _cmake_path(root, token, scope, tops))]
            for output in outputs:
                links.extend(Link("generated", output, target, role, INFERRED, path) for target, role in dict.fromkeys(targets)
                             if target != output)
    return links


@dataclass(frozen=True)
class BuildTarget:
    """An executable or a library a CMake file builds, with the source files of the repository it names."""

    name: str
    kind: str                  # executable or library
    stated: str                # the CMake file
    sources: tuple[str, ...]
    # An argument of its source list was not read (a variable the file does not set once with literal
    # values, a generator expression): the target may have sources that `sources` does not hold.
    unread: bool = False


@dataclass(frozen=True)
class BuildTest:
    """A test a CMake file adds: the target it runs, or the files of the repository its command names."""

    name: str
    target: str                # "" when the command is no build target
    runs: tuple[str, ...]
    stated: str


_BUILD_CALL = re.compile(r"\b(add_executable|add_library|target_sources|add_test)\s*\(((?:[^()]|\([^()]*\))*)\)", re.IGNORECASE)
_TARGET_WORDS = frozenset({
    "WIN32", "MACOSX_BUNDLE", "EXCLUDE_FROM_ALL", "STATIC", "SHARED", "MODULE", "OBJECT", "INTERFACE", "PRIVATE", "PUBLIC",
    "FILE_SET", "TYPE", "HEADERS", "BASE_DIRS", "FILES",
})
_TARGET_FILE = re.compile(r"\$<TARGET_FILE:([A-Za-z0-9_.+-]+)>")
_TEST_WORDS = frozenset({"WORKING_DIRECTORY", "CONFIGURATIONS", "COMMAND_EXPAND_LISTS"})
# What starts a comment or a quoted argument, what ends a quoted argument, what opens a bracket comment.
_CMAKE_MARK = re.compile(r'[#"]')
_CMAKE_QUOTE_END = re.compile(r'\\.|"', re.DOTALL)
_CMAKE_BRACKET = re.compile(r"\[(=*)\[")
# One argument of a call: quoted (its text is group 1) or bare.
_CMAKE_ARGUMENT = re.compile(r'"((?:[^"\\]|\\.)*)"|[^\s"]+', re.DOTALL)
_CMAKE_COMMAND = re.compile(r"(?<![\w.$<:{-])([A-Za-z_]\w*)[ \t]*\(")
_CMAKE_CALL_END = re.compile(r"((?:[^()]|\([^()]*\))*)\)")
_CMAKE_WORD = re.compile(r'[^\s()"]+')
_CMAKE_BLOCK_OPEN = frozenset({"if", "foreach", "while", "function", "macro", "block"})
_CMAKE_BLOCK_CLOSE = frozenset({"endif", "endforeach", "endwhile", "endfunction", "endmacro", "endblock"})
_CMAKE_WHOLE_VARIABLE = re.compile(r"\$\{(\w+)\}")
# A source in the build folder is a file a build step writes: no file of the repository, and nothing unread.
_CMAKE_BUILD_FOLDERS = ("${CMAKE_CURRENT_BINARY_DIR}", "${CMAKE_BINARY_DIR}", "${PROJECT_BINARY_DIR}")


def _cmake_code(text: str) -> str:
    """The text of a CMake file without its comments: `# ...` to the end of the line and the bracket
    comment `#[[ ... ]]` (`#[=[ ... ]=]`), which runs to the end of the file when nothing closes it. A `#`
    inside a quoted argument is text. One pass over the text."""
    kept: list[str] = []
    start = position = 0
    while True:
        mark = _CMAKE_MARK.search(text, position)
        if mark is None:
            break
        if mark.group() == '"':
            position = mark.end()
            while True:
                end = _CMAKE_QUOTE_END.search(text, position)
                if end is None:
                    position = len(text)
                    break
                position = end.end()
                if end.group() == '"':
                    break
            continue
        kept.append(text[start:mark.start()])
        bracket = _CMAKE_BRACKET.match(text, mark.end())
        if bracket is not None:
            closing = "]" + bracket.group(1) + "]"
            close = text.find(closing, bracket.end())
            position = len(text) if close < 0 else close + len(closing)
        else:
            newline = text.find("\n", mark.end())
            position = len(text) if newline < 0 else newline
        start = position
    kept.append(text[start:])
    return "".join(kept)


def _cmake_arguments(text: str) -> list[str]:
    """The arguments of a call: a quoted argument is one argument, given without its quotes."""
    return [match.group(1) if match.group(1) is not None else match.group() for match in _CMAKE_ARGUMENT.finditer(text)]


def _cmake_variables(code: str) -> dict[str, tuple[int, tuple[str, ...]]]:
    """Variable -> (where it is set, its values) for the variables the file sets once with `set(NAME a b c)`
    outside every block (`if`, `foreach`, `function` ...), and names in no other call (`list(APPEND NAME`,
    `file(GLOB NAME`, a second `set`). Nothing is evaluated: the values are the arguments as written."""
    named: dict[str, int] = {}
    for word in _CMAKE_WORD.findall(code):
        named[word] = named.get(word, 0) + 1
    found: dict[str, Optional[tuple[int, tuple[str, ...]]]] = {}
    depth = 0
    for command in _CMAKE_COMMAND.finditer(code):
        name = command.group(1).lower()
        if name in _CMAKE_BLOCK_OPEN:
            depth += 1
        elif name in _CMAKE_BLOCK_CLOSE:
            depth = max(0, depth - 1)
        elif name == "set":
            call = _CMAKE_CALL_END.match(code, command.end())
            arguments = _cmake_arguments(call.group(1)) if call is not None else []
            if not arguments:
                continue
            variable, values = arguments[0], [value for argument in arguments[1:] for value in argument.split(";") if value]
            literal = depth == 0 and variable not in found and values and "CACHE" not in values and "PARENT_SCOPE" not in values
            found[variable] = (command.start(), tuple(values)) if literal else None
    return {variable: stated for variable, stated in found.items() if stated is not None and named.get(variable) == 1}


def _cmake_substituted(
    arguments: Sequence[str], variables: dict[str, tuple[int, tuple[str, ...]]], position: int,
) -> list[str]:
    """The arguments with the variables of `_cmake_variables` set before `position` replaced: `${NAME}`
    alone by its values, `${NAME}` inside an argument by its value when it has one."""
    def values_of(name: str) -> tuple[str, ...]:
        stated = variables.get(name)
        return stated[1] if stated is not None and stated[0] < position else ()

    replaced: list[str] = []
    for argument in arguments:
        for part in argument.split(";") if ";" in argument else [argument]:
            whole = _CMAKE_WHOLE_VARIABLE.fullmatch(part)
            if whole is not None and values_of(whole.group(1)):
                replaced.extend(values_of(whole.group(1)))
            elif part:
                replaced.append(_CMAKE_WHOLE_VARIABLE.sub(
                    lambda match: values_of(match.group(1))[0] if len(values_of(match.group(1))) == 1 else match.group(), part))
    return replaced


def _cmake_source(root: str, token: str, source_folder: str, list_folder: str, tops: Sequence[str]) -> Optional[str]:
    """A CMake argument as a file of the repository. A relative path and `${CMAKE_CURRENT_SOURCE_DIR}` are
    taken from the folder of the list file that includes the CMake file, then from the folder of the file;
    `${CMAKE_CURRENT_LIST_DIR}` from the folder of the file; the project variables from the list folders above."""
    token = token.strip('"')
    if token.startswith("${CMAKE_CURRENT_LIST_DIR}"):
        return _cmake_path(root, token[len("${CMAKE_CURRENT_LIST_DIR}"):].lstrip("/\\"), list_folder, tops)
    return _cmake_path(root, token, source_folder, tops) or _cmake_path(root, token, list_folder, tops)


def cmake_targets(
    root: str, cmake_files: Iterable[str], read_text: Callable[[str], Optional[str]],
) -> tuple[list[BuildTarget], list[BuildTest]]:
    """The build targets and the tests the CMake files state literally: `add_executable`, `add_library`,
    `target_sources`, and `add_test(NAME <test> COMMAND <command> ...)` or `add_test(<test> <command> ...)`.
    A name written with a variable, an alias and an imported target are left out; so is what a function
    or a macro of the project adds, which no literal call states. A source list may name a variable that
    the same file sets once with literal values (`_cmake_variables`); a target with a source argument that
    could not be read is marked `unread`."""
    files = sorted(cmake_files)
    list_folders = {os.path.dirname(path) for path in files if os.path.basename(path) == "CMakeLists.txt"}
    sources: dict[str, dict[str, None]] = {}
    unread: set[str] = set()
    kinds: dict[str, tuple[str, str]] = {}
    tests: list[tuple[str, list[str], str, str, str, list[str]]] = []
    for path in files:
        text = read_text(path)
        if text is None:
            continue
        lowered = text.lower()
        if "add_executable" not in lowered and "add_library" not in lowered and "add_test" not in lowered \
                and "target_sources" not in lowered:
            continue
        here = os.path.dirname(path)
        above = []
        current = here
        while True:
            if current in list_folders:
                above.append(current)
            if not current:
                break
            current = os.path.dirname(current)
        scope = above[0] if above else here
        tops = list(reversed(above)) or [""]
        # A comment may hold a bracket: the calls are read from the text without its comments.
        code = _cmake_code(text)
        variables = _cmake_variables(code) if "${" in code else {}
        for call in _BUILD_CALL.finditer(code):
            command = call.group(1).lower()
            tokens = _cmake_arguments(call.group(2))
            if not tokens or "$" in tokens[0]:
                continue
            if command == "add_test":
                if tokens[0] == "NAME":
                    if len(tokens) < 4 or "COMMAND" not in tokens or "$" in tokens[1]:
                        continue
                    name = tokens[1]
                    words = tokens[tokens.index("COMMAND") + 1:]
                else:
                    name, words = tokens[0], tokens[1:]
                arguments: list[str] = []
                for word in words:
                    if word in _TEST_WORDS:
                        break
                    arguments.append(word)
                if arguments:
                    tests.append((name, arguments, path, scope, here, tops))
                continue
            if "ALIAS" in tokens or "IMPORTED" in tokens:
                continue
            name = tokens[0]
            if command != "target_sources":
                kinds.setdefault(name, ("executable" if command == "add_executable" else "library", path))
            found = sources.setdefault(name, {})
            for token in _cmake_substituted(tokens[1:], variables, call.start()):
                if token in _TARGET_WORDS:
                    continue
                source = _cmake_source(root, token, scope, here, tops)
                if source is not None:
                    found[source] = None
                elif "$" in token and not token.startswith(_CMAKE_BUILD_FOLDERS):
                    unread.add(name)
    targets = [
        BuildTarget(name, kind, stated, tuple(sources.get(name, ())), name in unread)
        for name, (kind, stated) in sorted(kinds.items())
    ]
    known = set(kinds)
    built: list[BuildTest] = []
    for name, arguments, stated, scope, here, tops in tests:
        # The target a test runs: the command itself, or the first `$<TARGET_FILE:<target>>` of its words.
        command = arguments[0].strip('"')
        named = [match.group(1) for word in arguments for match in _TARGET_FILE.finditer(word)]
        target = command if command in known else next((item for item in named if item in known), "")
        runs = [found for word in arguments if (found := _cmake_source(root, word, scope, here, tops)) is not None]
        if target or runs:
            built.append(BuildTest(name, target, tuple(dict.fromkeys(runs)), stated))
    return targets, sorted(built, key=lambda test: test.name)


def merged(links: Iterable[Link]) -> list[Link]:
    """One link per (kind, source, target): a declared one stands for an inferred one of the same pair."""
    best: dict[tuple[str, str, str], Link] = {}
    for link in links:
        key = (link.kind, link.source, link.target)
        known = best.get(key)
        if known is None or (known.basis == INFERRED and link.basis == DECLARED):
            best[key] = link
    return [best[key] for key in sorted(best)]
