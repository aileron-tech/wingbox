"""`impact --summary`: the short answer for a file that many others depend on."""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src"

# core/base.py is imported by 30 service files, 6 test files and 2 command-line scripts that nothing imports;
# a generator makes one more file from it.
FILES = {
    "core/__init__.py": "", "services/__init__.py": "", "jobs/__init__.py": "", "tests/__init__.py": "",
    "core/base.py": "VALUE = 1\n",
    **{f"services/part{number:02d}.py": "from core import base\n\nVALUE = base.VALUE\n" for number in range(30)},
    "jobs/hub.py": "".join(f"from services import part{number:02d}\n" for number in range(30)),
    **{f"tests/test_part{number}.py": "from core import base\n\n\ndef test_value():\n    assert base.VALUE == 1\n" for number in range(6)},
    "run_report.py": "from core import base\n\nprint(base.VALUE)\n",
    "run_export.py": "from core import base\n\nprint(base.VALUE)\n",
    "tools/make_table.py": "def main():\n    return 0\n",
    "core/table.py": "# Generated by tools/make_table.py; edit core/base.py\nTABLE = 1\n",
}


def _write(root: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8")


def _run(root: Path, *args: str) -> subprocess.CompletedProcess:
    environment = dict(os.environ, PYTHONPATH=str(SOURCE) + os.pathsep + os.environ.get("PYTHONPATH", ""), WINGBOX_JOBS="1")
    return subprocess.run([sys.executable, "-m", "wingbox", *args], capture_output=True, env=environment, cwd=str(root), timeout=180, text=True)


class ImpactSummaryTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        folder = tempfile.TemporaryDirectory()
        cls.addClassCleanup(folder.cleanup)
        cls.root = Path(os.path.realpath(folder.name))
        subprocess.run(["git", "init", "-q", str(cls.root)], check=True)
        _write(cls.root, FILES)
        _run(cls.root, "build", ".")

    def test_the_summary_counts_everything_and_names_a_few(self) -> None:
        """/* REQ-CS-166: `wingbox impact <file> [depth] --summary` answers in one short form instead of the complete list: `(impact-summary <file> :direct N :total M :depth D` with `(depths N ...)`, the number of dependents at each depth; `(kinds :generated N :tests N :entry-points N :other N)`, every dependent in one kind (made from the file or started by it; a test file; a file nothing else depends on; any other); `(folders (<folder> N) ... [:more N])`, the eight folders with the most dependents and the number of dependents elsewhere; `(first <file> ... [:more N])`, at most twenty files, nearest depth first and within a depth the generated files, the entry points, the tests, then the others; and `(full "<command>")`, the command that prints the complete list. The counts equal those of the complete answer. */"""
        answer = _run(self.root, "impact", "core/base.py", "2", "--summary")
        self.assertEqual(0, answer.returncode, answer.stderr)
        text = answer.stdout
        whole = json.loads(_run(self.root, "impact", "core/base.py", "2", "--json").stdout)["impact"][0]
        self.assertIn(f"(impact-summary core/base.py :direct {whole['direct']} :total {whole['total']} :depth 2", text)
        self.assertEqual((39, 40), (whole["direct"], whole["total"]))
        self.assertIn("(depths 39 1)", text)
        self.assertIn("(kinds :generated 1 :tests 6 :entry-points 3 :other 30)", text)   # jobs/hub.py is imported by nothing
        self.assertIn("(folders (services 30) (tests 6) (. 2) (core 1) (jobs 1))", text)
        first = text.split("(first ", 1)[1].split(")", 1)[0].split()
        self.assertEqual(["core/table.py", "run_export.py", "run_report.py", "tests/test_part0.py"], first[:4])
        self.assertEqual(":more", first[-2])
        self.assertEqual(20, len(first) - 2)
        self.assertEqual("20", first[-1])
        self.assertIn('(full "wingbox impact core/base.py 2")', text)
        self.assertLess(len(text.splitlines()), 12)
        self.assertNotIn("services/part29.py", text)

    def test_the_summary_in_the_other_forms(self) -> None:
        """/* REQ-CS-167: `--summary` with `--json` gives the same content per file (`summary` true, `direct`, `total`, `depth`, `depths`, `kinds`, `folders`, `more_in_other_folders`, `first`, `more`, `full`), with `--human` a text of a few lines, and with `--only tests` it counts and names the test files alone and, where the graph has build targets and tests, adds how many of them the change reaches. A file that is not in the graph answers as without the option; `--summary` with `--sexp` is an error. */"""
        document = json.loads(_run(self.root, "impact", "core/base.py", "--summary", "--json").stdout)["impact"][0]
        self.assertEqual(
            (True, 39, 40, 2, [39, 1], {"generated": 1, "tests": 6, "entry_points": 3, "other": 30}),
            (document["summary"], document["direct"], document["total"], document["depth"], document["depths"], document["kinds"]),
        )
        self.assertEqual({"folder": "services", "files": 30}, document["folders"][0])
        self.assertEqual((20, 20, "wingbox impact core/base.py 2"), (len(document["first"]), document["more"], document["full"]))
        self.assertNotIn("rows", document)
        human = _run(self.root, "impact", "core/base.py", "--summary", "--human").stdout
        self.assertIn("40 files depend on core/base.py within 2 hops (39 directly)", human)
        self.assertIn("6 test files", human)
        self.assertLess(len(human.splitlines()), 16)
        tests = _run(self.root, "impact", "core/base.py", "--summary", "--only", "tests").stdout
        self.assertIn("(impact-summary core/base.py :direct 6 :total 6 :depth 2 :only tests", tests)
        self.assertIn('(full "wingbox impact core/base.py 2 --only tests")', tests)
        missing = _run(self.root, "impact", "core/nothing.py", "--summary")
        self.assertEqual(1, missing.returncode)
        self.assertIn("(error no-match", missing.stdout)
        flat = _run(self.root, "impact", "core/base.py", "--summary", "--sexp")
        self.assertEqual(2, flat.returncode)
        self.assertIn("--summary", flat.stdout)


if __name__ == "__main__":
    unittest.main()
