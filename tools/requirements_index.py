#!/usr/bin/env python3
"""Write docs/assurance/requirements.md: every requirement the tests state, and the test that verifies it.

Every test of this repository says in its docstring which requirement it verifies:

    def test_a_missing_file_is_an_error(self):
        \"\"\"/* REQ-<AREA>-<n>: <the behaviour that must hold> */\"\"\"

This tool reads those docstrings from every Python file under tests/ (with `ast`: no test is
imported or run) and writes one table per area, the id without its number (`CS`, `REL`, `TS-WS`):
the id, the text, and the test as `file::Class::method`. A test without such a docstring is named
at the top of the page.

    python3 tools/requirements_index.py           rewrite the file
    python3 tools/requirements_index.py --check   exit 1 when the file is stale, write nothing

Run it after a test is added, removed or reworded; a test compares the committed file with the
output (REQ-DOC-004). Standard library only.
"""
from __future__ import annotations

import ast
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TESTS = Path("tests")
OUTPUT = Path("docs") / "assurance" / "requirements.md"
_REQUIREMENT = re.compile(r"\s*/\*\s*(?P<id>REQ-(?P<area>[A-Z0-9]+(?:-[A-Z0-9]+)*)-(?P<number>\d+))\s*:\s*(?P<text>.*?)\s*\*/\s*", re.S)
_CODE = re.compile(r"(`+[^`]*`+)")
# Outside code: what Markdown reads as emphasis, a tag, a strike-through or an escape.
_MARKUP = re.compile(r"[\\*<~$]|(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])")


@dataclass(frozen=True)
class Requirement:
    """A requirement as one test states it."""

    id: str
    area: str
    number: int
    text: str
    test: str  # file::Class::method


@dataclass(frozen=True)
class Found:
    """What the test files hold."""

    requirements: tuple[Requirement, ...]
    without: tuple[str, ...]  # tests whose docstring states no requirement


def _functions(node: ast.AST, trail: tuple[str, ...]):
    """Every function of a module with the names of the classes and functions around it."""
    for child in ast.iter_child_nodes(node):
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            yield child, trail + (child.name,)
            yield from _functions(child, trail + (child.name,))
        elif isinstance(child, ast.ClassDef):
            yield from _functions(child, trail + (child.name,))
        else:
            yield from _functions(child, trail)


def read_tests(repo: Path) -> Found:
    """The requirement of every function under tests/ that states one, and the tests that state none."""
    requirements: list[Requirement] = []
    without: list[str] = []
    # By the path as written with "/", so that the order is the same on every system.
    for relative in sorted(path.relative_to(repo).as_posix() for path in (repo / TESTS).rglob("*.py")):
        path = repo / relative
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=relative)
        for function, trail in _functions(tree, ()):
            name = "::".join((relative, *trail))
            match = _REQUIREMENT.fullmatch(ast.get_docstring(function, clean=False) or "")
            if match is not None:
                requirements.append(Requirement(match["id"], match["area"], int(match["number"]), match["text"], name))
            elif function.name.startswith("test"):
                without.append(name)
    return Found(tuple(requirements), tuple(without))


def cell(text: str) -> str:
    """Text as one table cell: one line, markup escaped outside code, every pipe escaped."""
    parts = _CODE.split(" ".join(text.split()))
    for index in range(0, len(parts), 2):
        parts[index] = _MARKUP.sub(lambda match: "&lt;" if match[0] == "<" else "\\" + match[0], parts[index])
    return "".join(parts).replace("|", "\\|")


def _count(number: int, noun: str) -> str:
    return f"{number} {noun}" + ("" if number == 1 else "s")


def render_found(found: Found) -> str:
    """The page for what the test files hold."""
    areas: dict[str, list[Requirement]] = {}
    for item in found.requirements:
        areas.setdefault(item.area, []).append(item)
    ids = {item.id for item in found.requirements}
    lines = [
        "# Requirements and the tests that verify them",
        "",
        "Generated by `tools/requirements_index.py` from the docstrings of `tests/`. Do not edit this file: "
        "run `python3 tools/requirements_index.py` after a test is added, removed or reworded "
        "(`--check` exits 1 when the file is stale; a test compares the two, REQ-DOC-004).",
        "",
        "Every test states the requirement it verifies in its docstring, `/* REQ-<AREA>-<n>: <behaviour> */`. "
        "Below, one table per area in the order of the area names; a requirement that several tests verify "
        "has one row per test, with the text of that test. To run one test: "
        "`python -m unittest tests.<file>.<Class>.<method>` with the requirements of AGENTS.md, section 2.",
        "",
        f"{_count(len(found.requirements), 'test')} carr{'ies' if len(found.requirements) == 1 else 'y'} a requirement id; "
        f"{_count(len(ids), 'id')} in {_count(len(areas), 'area')}.",
        "",
    ]
    if found.without:
        lines.append(f"{_count(len(found.without), 'test')} carr{'ies' if len(found.without) == 1 else 'y'} no requirement id:")
        lines.append("")
        lines += [f"- `{name}`" for name in found.without]
    else:
        lines.append("Every test carries a requirement id.")
    lines += ["", "| Area | Requirements | Tests | Test files |", "|---|---:|---:|---|"]
    for area in sorted(areas):
        items = areas[area]
        files = sorted({item.test.split("::", 1)[0] for item in items})
        lines.append(f"| [{area}](#{area.lower()}) | {len({item.id for item in items})} | {len(items)} | "
                     + ", ".join(f"`{name}`" for name in files) + " |")
    for area in sorted(areas):
        lines += ["", f"## {area}", "", "| Requirement | Behaviour | Test |", "|---|---|---|"]
        for item in sorted(areas[area], key=lambda item: (item.number, item.id, item.test)):
            lines.append(f"| {item.id} | {cell(item.text)} | `{item.test}` |")
    return "\n".join(lines) + "\n"


def render(repo: Path = REPO) -> str:
    """The page for the tests of a repository."""
    return render_found(read_tests(repo))


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if arguments not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    output = REPO / OUTPUT
    wanted = render(REPO).encode("utf-8")
    current = output.read_bytes() if output.is_file() else None
    if current == wanted:
        return 0
    if arguments:
        print(f"stale: {OUTPUT.as_posix()} (run python3 tools/requirements_index.py)")
        return 1
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(wanted)
    print(f"wrote {OUTPUT.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
